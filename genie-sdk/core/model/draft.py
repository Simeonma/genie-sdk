"""genie.core.model.draft -- the draft mirrors (the only legal home of
the draft (incomplete) state) + the promotion transform + the model
fingerprint.

- **Same names, same types** as the wire format, all fields optional,
  no value validation (locked by tests); the incomplete state
  (material not filled in after add) is legal here; value semantics
  exist only at the point of promotion (``to_wire → validate_for_ui``,
  the single validation surface). **One deliberate exception (Q13)**: a
  numeric slot also accepts an expression string (``"L*2"``) — the
  parameter-substitution entry; it is resolved by ``protocol.resolve`` at
  promotion, never here.
- Mirrors hand-write no field lists: everything is generated by
  reflection from ``genie_protocol._wire``; type / shape errors are
  blocked at assignment (``validate_assignment``).
- ``digest``: wire dict → canonical JSON (sort_keys + fixed
  separators) → sha256 hex; hashes only the model, not results /
  state; consumers = worker/run (staging writes, save writes, dirty
  checks).
"""
from __future__ import annotations

import hashlib
import inspect
import json
from typing import Any, Optional, Union, get_args, get_origin

from pydantic import BaseModel, ConfigDict, create_model

from genie_protocol import _wire

__all__ = ["DRAFT_OF", "to_wire", "digest"]


class _DraftBase(BaseModel):
    """Common draft shape: extra=forbid (misspelled fields fail loudly)
    + type checking at assignment; no value constraints at all (no
    value validation; the draft (incomplete) state is legal)."""

    model_config = ConfigDict(extra="forbid", validate_assignment=True)


def _bare(ann: Any) -> Any:
    """Strip Annotated: all constraint metadata from the wire format
    is discarded."""
    meta = getattr(ann, "__metadata__", None)
    return ann.__origin__ if meta is not None else ann


def _ann_classes(ann: Any) -> set:
    """All classes referenced in the annotation tree (for dependency
    analysis)."""
    ann = _bare(ann)
    origin = get_origin(ann)
    if origin is Union:
        out: set = set()
        for a in get_args(ann):
            out |= _ann_classes(a)
        return out
    if origin is not None:
        out = set()
        for a in get_args(ann):
            if inspect.isclass(a):
                out.add(a)
            else:
                out |= _ann_classes(a)
        return out
    return {ann} if inspect.isclass(ann) else set()


def _wire_classes() -> list:
    out = []
    for name, obj in vars(_wire).items():
        if (name.startswith("_") or not inspect.isclass(obj)
                or not issubclass(obj, BaseModel)):
            continue
        if obj.__module__ != _wire.__name__:
            continue                      # re-exported foreign types are not mirrored
        out.append(obj)
    return out


_WIRE_CLASSES = _wire_classes()
_WIRE_SET = set(_WIRE_CLASSES)


def _deps(cls) -> set:
    out = set()
    for f in cls.model_fields.values():
        out |= {c for c in _ann_classes(f.annotation) if c in _WIRE_SET}
    out.discard(cls)
    return out


def _ordered() -> list:
    """Topological order (nested classes are generated first); the
    wire format is a tree, no cycles."""
    done: list = []
    pending = set(_WIRE_CLASSES)
    while pending:
        ready = sorted((c for c in pending if not _deps(c) & pending),
                       key=lambda c: c.__name__)
        if not ready:
            raise RuntimeError("cycle in _wire model graph")
        done.extend(ready)
        pending.difference_update(ready)
    return done


# wire class → draft class (the single registry of mirrors; handle takes named drafts from here)
DRAFT_OF: dict = {}


def _draftify_inner(ann: Any) -> Any:
    """wire annotation → draft annotation (without the outer Optional):
    nested models become drafts, constraints stripped bare; Literal /
    primitive types are kept as-is — one deliberate exception: a numeric
    slot also takes an **expression string** (``"L*2"``, resolved against
    the parameters table at the promotion point, Q13)."""
    ann = _bare(ann)
    if ann in DRAFT_OF:
        return DRAFT_OF[ann]
    if ann in (float, int):
        # COMSOL-style substitution entry: the name lives in f.parameters, the
        # slot holds the expression. Resolution stays in protocol.resolve.
        return Union[ann, str]
    origin = get_origin(ann)
    if origin is Union:
        args = tuple(a for a in get_args(ann) if a is not type(None))
        args = tuple(_draftify_inner(a) for a in args)
        return Union[args] if len(args) > 1 else args[0]
    if origin is list:
        args = get_args(ann)
        return list[_draftify_inner(args[0])] if args else list
    if origin is dict:
        args = get_args(ann)
        return dict[args[0], _draftify_inner(args[1])] if len(args) == 2 else dict
    if origin is tuple:
        args = get_args(ann)
        if args and args[-1] is Ellipsis:
            return tuple[_draftify_inner(args[0]), ...]
        return tuple[tuple(_draftify_inner(a) for a in args)]
    return ann


def _draftify(ann: Any) -> Any:
    """Wrap in a whole layer of Optional (all draft fields are
    optional)."""
    return Optional[_draftify_inner(ann)]


for _cls in _ordered():
    _name = (_cls.__name__[:-4] if _cls.__name__.endswith("Spec")
             else _cls.__name__) + "Draft"
    DRAFT_OF[_cls] = create_model(
        _name, __base__=_DraftBase,
        **{n: (_draftify(f.annotation), None)
           for n, f in _cls.model_fields.items()})


def to_wire(value: Any) -> Any:
    """Promotion: draft value → wire-format dict (**Nones stripped**,
    recursive); raw dicts pass through the same recursion (a bare dict
    assigned per-key into boundary is likewise absorbed). The result
    must then go through ``validate_for_ui`` (the single validation
    surface)."""
    if isinstance(value, BaseModel):
        out = {}
        for fname in type(value).model_fields:
            v = getattr(value, fname)
            if v is not None:
                out[fname] = to_wire(v)
        return out
    if isinstance(value, dict):
        return {k: to_wire(v) for k, v in value.items()}
    if isinstance(value, list):
        return [to_wire(v) for v in value]
    if isinstance(value, tuple):
        return tuple(to_wire(v) for v in value)
    return value


def digest(wire_dict: dict) -> str:
    """Model fingerprint: promotion output → canonical JSON
    (``sort_keys`` + fixed separators ``(",", ":")``) → sha256 hex.
    **Hashes only the model** (the wire dict itself -- not results /
    state; the input is the boundary). Determinism is locked by
    tests."""
    payload = json.dumps(wire_dict, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()
